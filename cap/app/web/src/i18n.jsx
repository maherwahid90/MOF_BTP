const I18nContext = createContext(null)

function initialLanguage() {
  try { return localStorage.getItem('lang') === 'en' ? 'en' : 'ar' } catch { return 'ar' }
}

export function I18nProvider({ children }) {
  const [lang, setLang] = useState(initialLanguage)
  setApiLanguage(lang)

  useEffect(() => {
    document.documentElement.lang = lang
    document.documentElement.dir = lang === 'ar' ? 'rtl' : 'ltr'
    try { localStorage.setItem('lang', lang) } catch { /* storage unavailable */ }
  }, [lang])

  const value = useMemo(() => {
    const locale = lang === 'ar' ? 'ar-SA-u-ca-gregory-nu-latn' : 'en-GB'
    const amountFormat = new Intl.NumberFormat(locale, { minimumFractionDigits: 2, maximumFractionDigits: 2 })
    return {
      lang,
      setLang,
      t: key => texts[lang][key] ?? key,
      formatAmount: value => (value == null || value === '' ? '' : amountFormat.format(Number(value))),
      formatDateTime: value => (value ? new Date(value).toLocaleString(locale) : '')
    }
  }, [lang])

  return <I18nContext.Provider value={value}>{children}</I18nContext.Provider>
}

export const useI18n = () => useContext(I18nContext)
